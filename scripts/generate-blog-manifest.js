#!/usr/bin/env node
/*
 * Generates src/features/blog/posts.generated.js from content/blog/*.md.
 *
 * Runs as part of `prestart` and `prebuild` so dev server and production
 * builds always see the latest posts. Pure build-time — gray-matter parses
 * YAML frontmatter and the resulting JS module is statically importable
 * by the React bundle.
 *
 * Each post becomes:
 *   { slug, title, description, date, updated, author, authorUrl,
 *     tags, ogImage, body, draft, readTimeMinutes }
 *
 * Drafts (frontmatter `draft: true`) are skipped at build time so they
 * never ship to production. Posts dated in the future are also skipped.
 */

const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const ROOT = path.resolve(__dirname, '..');
const BLOG_DIR = path.join(ROOT, 'content', 'blog');
const OUT_FILE = path.join(ROOT, 'src', 'features', 'blog', 'posts.generated.js');

const REQUIRED_FIELDS = ['title', 'description', 'date', 'tags'];

function estimateReadTime(text) {
    // 200 words/min is the standard reading speed assumption for blog content.
    const words = text.trim().split(/\s+/).length;
    return Math.max(1, Math.round(words / 200));
}

function parsePost(filePath) {
    const raw = fs.readFileSync(filePath, 'utf8');
    const { data, content } = matter(raw);

    const filename = path.basename(filePath, path.extname(filePath));
    const slug = data.slug || filename;

    const missing = REQUIRED_FIELDS.filter(f => data[f] === undefined || data[f] === null);
    if (missing.length) {
        throw new Error(`[blog] ${filename}: missing required frontmatter: ${missing.join(', ')}`);
    }

    return {
        slug,
        title: String(data.title),
        description: String(data.description),
        date: new Date(data.date).toISOString().slice(0, 10),
        updated: data.updated ? new Date(data.updated).toISOString().slice(0, 10) : null,
        author: data.author || 'N3FitBook Team',
        authorUrl: data.authorUrl || 'https://www.n3fitbook.in',
        tags: Array.isArray(data.tags) ? data.tags : [],
        ogImage: data.ogImage || '/og-image.png',
        draft: data.draft === true,
        body: content,
        readTimeMinutes: estimateReadTime(content),
    };
}

function main() {
    if (!fs.existsSync(BLOG_DIR)) {
        console.warn(`[blog] ${BLOG_DIR} not found — writing empty manifest`);
        fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
        fs.writeFileSync(OUT_FILE, '// auto-generated by scripts/generate-blog-manifest.js\nexport const posts = [];\n');
        return;
    }

    const today = new Date().toISOString().slice(0, 10);

    const files = fs.readdirSync(BLOG_DIR)
        .filter(f => f.endsWith('.md') || f.endsWith('.mdx'))
        .map(f => path.join(BLOG_DIR, f));

    const all = files.map(parsePost);

    const published = all.filter(p => {
        if (p.draft) return false;
        if (p.date > today) return false; // future-dated posts skip until their day
        return true;
    });

    // Sort newest first — the index page paginates from this order.
    published.sort((a, b) => b.date.localeCompare(a.date));

    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(
        OUT_FILE,
        `// AUTO-GENERATED by scripts/generate-blog-manifest.js — do not edit by hand.\n` +
        `// Source: content/blog/*.md. Re-run via: npm run generate-blog-manifest\n` +
        `\n` +
        `export const posts = ${JSON.stringify(published, null, 2)};\n`,
    );

    const skipped = all.length - published.length;
    console.log(
        `posts.generated.js: ${published.length} post(s)` +
        (skipped > 0 ? ` (${skipped} skipped — drafts or future-dated)` : '')
    );
}

main();
